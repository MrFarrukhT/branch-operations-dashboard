import { AvButton } from '../ui/controls';
import { useDataset } from '../data/DatasetContext';
import { toCleanJson, toReportJson } from '../data/outputs';
import type { IssueSeverity } from '../data/types';
import { useI18n } from '../lib/i18n';
import { Card, CardHeader, Icon, cx } from './ui';

const SEVERITY: Record<IssueSeverity, string> = {
  high: 'bg-signal text-on-button',
  medium: 'border border-ink text-ink',
  low: 'border border-line-strong text-ink-2',
  info: 'bg-surface-2 text-ink-2',
};

const download =
  'tap inline-flex min-h-8 items-center gap-1.5 border border-line-strong px-2.5 font-medium text-ink-2 hover:border-accent hover:text-ink';

/**
 * The data-quality section, short: one plain line per finding (what was wrong, how many rows, what
 * was done), the checks folded behind their count. Every line is generated by the cleaner (src/data/clean.ts, `summary`) from
 * the data in use, the sample or an upload; the long version (found, handled, why) is in docs/DATA_QUALITY.md.
 */
export function DataQuality() {
  const { t } = useI18n();
  const data = useDataset();
  const { checks, issues, source } = data;
  const passed = checks.filter((c) => c.passed).length;
  const failed = checks.filter((c) => !c.passed);
  const base = data.origin === 'sample' ? 'branch_operations_2025' : data.fileName.replace(/\.[^.]+$/, '');
  const save = (text: string, name: string) => {
    const url = URL.createObjectURL(new Blob([text], { type: 'application/json' }));
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };

  return (
    <Card labelledBy="dq-title">
      <span id="data-quality" className="block scroll-mt-24" />
      <CardHeader
        id="dq-title"
        title={t.dqTitle}
        subtitle={t.dqSub(source.dataRows, data.fileName, issues.length)}
        actions={
          <div className="no-print flex flex-wrap gap-2 text-[12.5px]">
            <AvButton type="button" className={download} onClick={() => save(toCleanJson(data), `${base}.json`)}>
              {Icon.download('size-3.5')} {t.cleanJson}
            </AvButton>
            <AvButton type="button" className={download} onClick={() => save(toReportJson(data), `${base}-report.json`)}>
              {Icon.download('size-3.5')} {t.reportJson}
            </AvButton>
          </div>
        }
      />

      <div className="px-4 pt-3 sm:px-5">
        <details className="group/checks border border-line" data-checks>
          <summary className="tap flex cursor-pointer list-none flex-wrap items-center gap-x-2.5 gap-y-1 px-3 py-2 text-[13.5px] marker:hidden">
            <span className="text-muted transition-transform group-open/checks:rotate-90">›</span>
            <span className="font-semibold text-ink">{t.checksPassed(passed, checks.length)}</span>
            {failed.length > 0 && (
              <span className="min-w-0 text-[12.5px] text-bad">
                {Icon.cross('inline size-3.5 align-[-2px]')} {failed.map((c) => c.label).join(' · ')}
              </span>
            )}
          </summary>
          <ul className="divide-y divide-line border-t border-line" aria-label={t.checksTitle}>
            {checks.map((c) => (
              <li key={c.id} className="flex gap-2.5 px-3 py-2 text-[13px]">
                <span className={cx('mt-0.5', c.passed ? 'text-good' : 'text-bad')}>{c.passed ? Icon.check() : Icon.cross()}</span>
                <span className="min-w-0 text-ink">
                  {c.label}
                  <span className="sr-only">: {c.passed ? t.passed : t.failed}</span>
                </span>
              </li>
            ))}
          </ul>
        </details>
      </div>

      <ol className="mx-4 mt-3 mb-4 divide-y divide-line border-y border-line sm:mx-5 sm:mb-5">
        {issues.map((issue) => (
          <li key={issue.id} className="flex items-baseline gap-3 py-2.5 text-[13.5px] leading-snug" data-finding={issue.id}>
            <span
              className={cx(
                'w-[62px] shrink-0 py-0.5 text-center font-mono text-[10.5px] font-medium tracking-[0.04em] uppercase',
                SEVERITY[issue.severity],
              )}
            >
              {t.severity[issue.severity]}
            </span>
            <span className="min-w-0 text-ink-2">{issue.summary}</span>
          </li>
        ))}
      </ol>
    </Card>
  );
}
