import { QUARTERS, REGIONS, TIERS, type CleanResult } from './types';

/** Render the cleaning result as a Markdown data-quality report (docs/DATA_QUALITY.md). */
export function renderDataQualityMarkdown(result: CleanResult): string {
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  push(
    '# Data-quality report',
    '',
    `> Generated by \`pnpm data\` from \`data/raw/${result.source.file}\` — do not edit by hand.`,
    '',
    `- Source rows: **${result.source.dataRows}**`,
    `- Clean records: **${result.records.length}**`,
    `- Rejected rows: **${result.rejected.length}**`,
    `- Issues found: **${result.issues.length}**`,
    '',
    '## Issues and how they were handled',
    '',
  );

  result.issues.forEach((issue, i) => {
    push(
      `### ${i + 1}. ${issue.title}`,
      '',
      `**Severity:** ${issue.severity} · **Category:** ${issue.category}` +
        (issue.recordIds.length ? ` · **Records:** ${issue.recordIds.join(', ')}` : ''),
      '',
      `- **In short:** ${issue.summary}`,
      `- **Found:** ${issue.detail}`,
      `- **Handling:** ${issue.handling}`,
      `- **Why:** ${issue.rationale}`,
      '',
    );
  });

  push('## Coverage (record id per quarter × region × tier)', '');
  const segments = REGIONS.flatMap((r) => TIERS.map((t) => ({ r, t })));
  push(`| Quarter | ${segments.map((s) => `${s.r} · ${s.t}`).join(' | ')} |`);
  push(`|---|${segments.map(() => '---').join('|')}|`);
  for (const q of QUARTERS) {
    const cells = segments.map(({ r, t }) => {
      const cell = result.coverage.find((c) => c.quarter === q && c.region === r && c.tier === t);
      return cell?.recordId != null ? String(cell.recordId) : '**missing**';
    });
    push(`| ${q} | ${cells.join(' | ')} |`);
  }
  push('', '## Validation checks', '', '| Check | Result | Detail |', '|---|---|---|');
  for (const c of result.checks) push(`| ${c.label} | ${c.passed ? 'pass' : '**fail**'} | ${c.detail} |`);
  push('');
  return lines.join('\n');
}
